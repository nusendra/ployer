use super::*;

use std::sync::atomic::{AtomicU32, Ordering};

/// A template body small enough to hash by hand in a test, but complete
/// enough to deserialise into a `Template`.
const BODY: &str = "slug: fixture\nname: Fixture\ndescription: d\ncategory: database\nversion: 1\ncompose: \"services: {}\"\n";

/// Unique scratch directory per test, removed on drop so tests never see each
/// other's cache files regardless of the order they run in.
struct Scratch(PathBuf);

impl Scratch {
    fn new() -> Self {
        static COUNTER: AtomicU32 = AtomicU32::new(0);
        let unique = format!(
            "ployer-registry-tests-{}-{}",
            std::process::id(),
            COUNTER.fetch_add(1, Ordering::SeqCst)
        );
        let path = std::env::temp_dir().join(unique);
        std::fs::create_dir_all(&path).expect("scratch dir");
        Self(path)
    }
}

impl Drop for Scratch {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

fn registry(cache_dir: &Path) -> Registry {
    Registry::new(RegistryConfig {
        // Never reached: every test here exercises the disk cache only.
        registry_url: "http://127.0.0.1:1/unused".to_string(),
        cache_dir: cache_dir.to_path_buf(),
        cache_ttl: Duration::from_secs(15),
    })
}

fn entry(sha256: &str) -> IndexEntry {
    IndexEntry {
        slug: "fixture".to_string(),
        name: "Fixture".to_string(),
        description: "d".to_string(),
        category: "database".to_string(),
        tags: vec![],
        version: serde_json::json!(1),
        sha256: sha256.to_string(),
        url: "https://ployer.nusendra.com/templates/fixture.yaml".to_string(),
    }
}

// ---------------------------------------------------------------------------
// Hashing
// ---------------------------------------------------------------------------

#[test]
fn sha256_hex_matches_the_standard_digest() {
    // Pins both the algorithm and the lowercase hex encoding; the registry
    // index is generated by a separate Node script that must agree exactly.
    assert_eq!(
        sha256_hex(b"abc"),
        "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
    );
    assert_eq!(
        sha256_hex(b""),
        "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
    );
}

// ---------------------------------------------------------------------------
// Cache file naming
//
// The cache key has to change when the template changes, or an upgraded
// template is masked forever by the copy already on disk.
// ---------------------------------------------------------------------------

#[test]
fn cache_filename_is_namespaced_by_slug_and_hash_prefix() {
    let scratch = Scratch::new();
    let hash = sha256_hex(BODY.as_bytes());
    let path = registry(&scratch.0).template_path(&entry(&hash));

    assert_eq!(
        path.file_name().unwrap().to_str().unwrap(),
        format!("fixture-{}.yaml", &hash[..16])
    );
}

#[test]
fn a_new_template_version_gets_a_new_cache_file() {
    let scratch = Scratch::new();
    let reg = registry(&scratch.0);

    let old = reg.template_path(&entry(&sha256_hex(b"version one")));
    let new = reg.template_path(&entry(&sha256_hex(b"version two")));

    assert_ne!(
        old, new,
        "a changed template must not be served from the previous cache entry"
    );
}

#[test]
fn index_is_cached_next_to_the_templates() {
    let scratch = Scratch::new();
    assert_eq!(registry(&scratch.0).index_path(), scratch.0.join("index.json"));
}

// ---------------------------------------------------------------------------
// Disk cache integrity
//
// `get()` returns a cached template without re-downloading it, so the cached
// bytes are re-hashed on every read. A tampered cache file must not be parsed.
// ---------------------------------------------------------------------------

#[tokio::test]
async fn cached_template_is_returned_when_its_hash_still_matches() {
    let scratch = Scratch::new();
    let reg = registry(&scratch.0);
    let e = entry(&sha256_hex(BODY.as_bytes()));

    reg.write_disk_template(&e, BODY).await.expect("cache write");
    let template = reg.read_disk_template(&e).await.expect("cache hit");

    assert_eq!(template.slug, "fixture");
}

#[tokio::test]
async fn a_tampered_cache_file_is_rejected_rather_than_parsed() {
    let scratch = Scratch::new();
    let reg = registry(&scratch.0);
    let e = entry(&sha256_hex(BODY.as_bytes()));

    reg.write_disk_template(&e, BODY).await.expect("cache write");
    // Someone edits the cached file in place, keeping the same filename.
    let tampered = BODY.replace("Fixture", "Evil");
    assert_ne!(tampered, BODY, "the tamper must actually change the bytes");
    std::fs::write(reg.template_path(&e), &tampered).expect("tamper");

    match reg.read_disk_template(&e).await {
        Err(TemplateError::HashMismatch { slug, expected, actual }) => {
            assert_eq!(slug, "fixture");
            assert_eq!(expected, e.sha256);
            assert_eq!(actual, sha256_hex(tampered.as_bytes()));
            assert_ne!(expected, actual);
        }
        Err(other) => panic!("expected HashMismatch, got {other:?}"),
        Ok(_) => panic!("a tampered cache file must not be returned"),
    }
}

#[tokio::test]
async fn a_cache_miss_is_an_error_so_the_caller_refetches() {
    let scratch = Scratch::new();
    let reg = registry(&scratch.0);

    // `get()` treats any Err from the disk cache as "go to the network".
    assert!(reg
        .read_disk_template(&entry(&sha256_hex(b"never cached")))
        .await
        .is_err());
}

#[tokio::test]
async fn the_cache_directory_is_created_on_first_write() {
    let scratch = Scratch::new();
    let nested = scratch.0.join("deeply/nested/cache");
    let reg = registry(&nested);
    let e = entry(&sha256_hex(BODY.as_bytes()));

    assert!(!nested.exists());
    reg.write_disk_template(&e, BODY).await.expect("cache write");
    assert!(nested.join(format!("fixture-{}.yaml", &e.sha256[..16])).exists());
}

// ---------------------------------------------------------------------------
// Index disk fallback — what the dashboard shows when the registry is down
// ---------------------------------------------------------------------------

#[tokio::test]
async fn the_index_survives_a_write_read_round_trip() {
    let scratch = Scratch::new();
    let reg = registry(&scratch.0);
    let index = RegistryIndex {
        schema_version: 1,
        generated_at: "2026-10-19T10:03:38.550Z".to_string(),
        templates: vec![entry(&sha256_hex(BODY.as_bytes()))],
    };

    reg.write_disk_index(&index).await.expect("index write");
    let restored = reg.read_disk_index().await.expect("index read");

    assert_eq!(restored.schema_version, 1);
    assert_eq!(restored.templates.len(), 1);
    assert_eq!(restored.templates[0].slug, "fixture");
    assert_eq!(restored.templates[0].sha256, index.templates[0].sha256);
}

#[tokio::test]
async fn reading_an_absent_index_fails_instead_of_returning_an_empty_catalog() {
    // An empty catalog would render as "no services available", which looks
    // like a deliberate state rather than a registry outage.
    let scratch = Scratch::new();
    assert!(registry(&scratch.0).read_disk_index().await.is_err());
}

#[tokio::test]
async fn a_corrupt_index_on_disk_is_an_error_not_a_panic() {
    let scratch = Scratch::new();
    let reg = registry(&scratch.0);
    std::fs::write(reg.index_path(), b"{ not json").expect("write corrupt index");

    assert!(reg.read_disk_index().await.is_err());
}
